func (c *Config) normalize() error {
	var err error
	if err = c.normalizeAPIKeys(); err != nil {
		return err
	}
	if c.SoftRateDur, err = time.ParseDuration(c.Cooldown.SoftRate); err != nil {
		return fmt.Errorf("cooldown.soft_rate: %w", err)
	}
	// 空值回落默认 2h（Default() 已置值；此兜底覆盖显式 "" 与 Default() 被绕过的场景）。
	if c.Cooldown.SoftRateMax == "" {
		c.Cooldown.SoftRateMax = "2h"
	}
	if c.SoftRateMaxDur, err = time.ParseDuration(c.Cooldown.SoftRateMax); err != nil {
		return fmt.Errorf("cooldown.soft_rate_max: %w", err)
	}
	if c.BreakerCooldownDur, err = time.ParseDuration(c.Pool.BreakerCooldown); err != nil {
		return fmt.Errorf("pool.breaker_cooldown: %w", err)
	}
	if c.BreakerCooldownMaxD, err = time.ParseDuration(c.Pool.BreakerCooldownMax); err != nil {
		return fmt.Errorf("pool.breaker_cooldown_max: %w", err)
	}
	if c.DegradeCooldownDur, err = time.ParseDuration(c.Pool.DegradeCooldown); err != nil {
		return fmt.Errorf("pool.degrade_cooldown: %w", err)
	}
	if c.DegradeCooldownMaxD, err = time.ParseDuration(c.Pool.DegradeCooldownMax); err != nil {
		return fmt.Errorf("pool.degrade_cooldown_max: %w", err)
	}
	if c.SessionTTL, err = time.ParseDuration(c.SessionSticky.TTL); err != nil {
		return fmt.Errorf("session_sticky.ttl: %w", err)
	}
	if c.SessionGCInterval, err = time.ParseDuration(c.SessionSticky.GCInterval); err != nil {
		return fmt.Errorf("session_sticky.gc_interval: %w", err)
	}
	// 快过期窗口：空 = 禁用（ExpiringSoonDur 0）；非空必须可解析（拼写错误 fail fast）。
	if c.Pool.ExpiringSoon != "" {
		if c.ExpiringSoonDur, err = time.ParseDuration(c.Pool.ExpiringSoon); err != nil {
			return fmt.Errorf("pool.expiring_soon: %w", err)
		}
	}
	// costTier 探索窗口（issue #136）：空值回落默认 30m（Default 已置；此兜底覆盖
	// 显式 ""）；"0" 是合法值（关停，完全回到现状行为），不回落；负值钳 0 同关停
	//（"−5m" 无合理语义）。
	if c.Pool.CostExploreInterval == "" {
		c.Pool.CostExploreInterval = "30m"
	}
	if c.CostExploreIntervalDur, err = time.ParseDuration(c.Pool.CostExploreInterval); err != nil {
		return fmt.Errorf("pool.cost_explore_interval: %w", err)
	}
	if c.CostExploreIntervalDur < 0 {
		c.CostExploreIntervalDur = 0
	}
	if c.Pool.BreakerThreshold <= 0 {
		c.Pool.BreakerThreshold = 3
	}
	// 连败降权参数缺省归一（非法/未设置回落默认，与 breaker_threshold 同风格）。
	if c.Pool.DegradeThreshold <= 0 {
		c.Pool.DegradeThreshold = 5
	}
	if c.Pool.DegradeCooldown == "" {
		c.Pool.DegradeCooldown = "10m"
	}
	if c.Pool.DegradeCooldownMax == "" {
		c.Pool.DegradeCooldownMax = "2h"
	}
	// global 在途分档：0/负数视为未设置回落默认 2（WAF 403 修复 P1-1）。
	if c.Pool.MaxInFlightGlobal <= 0 {
		c.Pool.MaxInFlightGlobal = 2
	}
	if c.Pool.IdleWeightPerHour <= 0 {
		c.Pool.IdleWeightPerHour = 0.5
	}
	if c.Pool.IdleWeightMax <= 0 {
		c.Pool.IdleWeightMax = 5.0
	}
	if c.Upstream.TimeoutSeconds <= 0 {
		c.Upstream.TimeoutSeconds = 120
	}
	// header 缺省回落 timeout（保"首字节前换号"既有语义）；idle 缺省走内置大值。
	// 任务书约定：0 一律视为"未设置"走默认，真正的"禁用"留待后续（避免歧义）。
	if c.Upstream.HeaderTimeoutSeconds <= 0 {
		c.Upstream.HeaderTimeoutSeconds = c.Upstream.TimeoutSeconds
	}
	if c.Upstream.IdleTimeoutSeconds <= 0 {
		c.Upstream.IdleTimeoutSeconds = 300
	}
	// 模型域路由：prefer 只认 global，其余（空/拼错）一律 cn——缺省值与去前缀前的
	// 裸名语义一致；pins 重建一张干净表（非法值丢弃、键去空白、不别名调用方的 map，
	// 满足 livecfg 快照"Store 后不可改"的约定）。配错不该导致路由漂移。
	if c.ModelRealm.Prefer != "global" {
		c.ModelRealm.Prefer = "cn"
	}
	if len(c.ModelRealm.Pins) > 0 {
		pins := make(map[string]string, len(c.ModelRealm.Pins))
		for name, realm := range c.ModelRealm.Pins {
			name = strings.TrimSpace(name)
			if name == "" || (realm != "cn" && realm != "global") {
				continue
			}
			pins[name] = realm
		}
		c.ModelRealm.Pins = pins
	}
	if !strings.HasPrefix(c.Listen, ":") && !strings.Contains(c.Listen, ":") {
		c.Listen = ":" + c.Listen
	}
	// 空数组与 null 反序列化后覆盖掉 Default() 的排程值（键缺席才保留），在此补齐。
	// 空 = 未配置 → 回落默认；「禁用」一律走 *_enabled=false，两者互不混淆。
	if len(c.Schedule.CheckinHours) == 0 {
		c.Schedule.CheckinHours = []int{9, 21}
	}
	if len(c.Schedule.TravelHours) == 0 {
		c.Schedule.TravelHours = []int{9, 21}
	}
	if len(c.Schedule.ActivityHours) == 0 {
		c.Schedule.ActivityHours = []int{10}
	}
	if len(c.Schedule.KeepaliveHours) == 0 {
		c.Schedule.KeepaliveHours = []int{22}
	}
	if len(c.Schedule.BlackcatHours) == 0 {
		c.Schedule.BlackcatHours = []int{23}
	}
	// 余额后台刷新：启用时 minutes<=0 回落默认 5；关闭时 interval 保持 0（不启动）。
	if c.Schedule.BalanceRefreshEnabled {
		if c.Schedule.BalanceRefreshMinutes <= 0 {
			c.Schedule.BalanceRefreshMinutes = 5
		}
		c.BalanceRefreshInterval = time.Duration(c.Schedule.BalanceRefreshMinutes) * time.Minute
	}
	// 验活：model/prompt 为空一律回落默认——空的 model 会让上游 400，空的 prompt 也一样，
	// 而这两种"配置漏填"的表现是"所有账号验活全失败 → 全部被自动禁用"，
	// 属于最坏的一类误伤，必须在配置层就堵住。
	if c.Probe.Enabled {
		if c.Probe.IntervalMinutes <= 0 {
			c.Probe.IntervalMinutes = 120
		}
		if strings.TrimSpace(c.Probe.Model) == "" {
			c.Probe.Model = "hy3"
		}
		if strings.TrimSpace(c.Probe.Prompt) == "" {
			c.Probe.Prompt = "hi"
		}
		if c.Probe.FailThreshold <= 0 {
			c.Probe.FailThreshold = 3
		}
		c.Probe.Model = strings.TrimSpace(c.Probe.Model)
		c.Probe.Prompt = strings.TrimSpace(c.Probe.Prompt)
		c.ProbeInterval = time.Duration(c.Probe.IntervalMinutes) * time.Minute
	}
	if err := c.validateScheduleHours(); err != nil {
		return err
	}
	return c.normalizePrompt()
}

// normalizePrompt 校验 prompt.mode 并按 file 加载提示词文本（custom/append 模式）。
//
// mode 非法（非 passthrough/custom/append）启动报错，避免静默回落到某一分支；
// custom/append 模式下 file 非空但不可读 → 报错（fail fast），file 空 → 用内置默认
// （两模式共用同一加载路径，PromptText 均非空）。
// passthrough 模式不加载文本（透传客户端原始 system，文本在降级时用 prompt.Degraded）。
func (c *Config) normalizePrompt() error {
	switch m := strings.ToLower(strings.TrimSpace(c.Prompt.Mode)); m {
	case "", "passthrough":
		c.Prompt.Mode = "passthrough"
	case "custom":
		c.Prompt.Mode = "custom"
	case "append":
		c.Prompt.Mode = "append"
	default:
		return fmt.Errorf("prompt.mode: %q 不是合法值（passthrough / custom / append）", c.Prompt.Mode)
	}
	if c.Prompt.Mode == "custom" || c.Prompt.Mode == "append" {
		text, err := prompt.Load(c.Prompt.Mode, c.Prompt.File)
		if err != nil {
			return err
		}
		c.PromptText = text
	}
	return nil
}

// validateScheduleHours 校验排程小时落在 0-23。
//
// 为什么不用 `[-1]` 之类的哨兵值表意"禁用"：非法小时被静默吞掉时，用户以为关掉了签到，
// 实际可能被当成另一个整点照常执行；这里直接快速失败，并在错误信息里指向正确的开关
// （checkin_enabled / keepalive_enabled），避免用户靠猜哨兵值来配。
func (c *Config) validateScheduleHours() error {
	if err := checkHourRange("schedule.checkin_hours", "checkin_enabled", c.Schedule.CheckinHours); err != nil {
		return err
	}
	if err := checkHourRange("schedule.travel_hours", "travel_enabled", c.Schedule.TravelHours); err != nil {
		return err
	}
	if err := checkHourRange("schedule.activity_hours", "activity_enabled", c.Schedule.ActivityHours); err != nil {
		return err
	}
	if err := checkHourRange("schedule.keepalive_hours", "keepalive_enabled", c.Schedule.KeepaliveHours); err != nil {
		return err
	}
	return checkHourRange("schedule.blackcat_hours", "blackcat_enabled", c.Schedule.BlackcatHours)
}

func checkHourRange(field, switchKey string, hours []int) error {
	for _, h := range hours {
		if h < 0 || h > 23 {
			return fmt.Errorf("%s: %d 不是合法小时（0-23）；如要关闭该任务请设 schedule.%s=false", field, h, switchKey)
		}
	}
	return nil
}

// DefaultAPIKeyName 密钥没配名字时的显示名。
//
// 刻意用「默认」而不是「我」之类的人称：面板是一个可能被多个人看的地方，
// 由代码替用户决定"谁是「我」"既越权又会读起来别扭。
// 名字一律由用户在设置页自己填；没填就老实显示「默认」。
const DefaultAPIKeyName = "默认"

// maxKeyNameRunes 密钥名字的长度上限（按字符计）。名字进面板表格，过长会把
// 「密钥」那一列撑开，且没有实际信息量。
const maxKeyNameRunes = 24

// MaxAPIKeys 额外密钥条数上限。密钥表在每次请求都要线性遍历做常量时间比较，
// 不设上限等于给了一个免费的自伤开关；家用场景几个人足够。
const MaxAPIKeys = 16

// ClientKeys 返回网关 /v1 鉴权用 密钥 → 名字 表（含主密钥）。
//
// 主密钥名恒定来自 APIKeyName，且**后写入**：即便 api_keys 里塞了同一个密钥，
// 也覆盖不掉主密钥的名字（避免配置手滑把自己的流水算到别人头上）。
// 返回的 map 每次都是新副本，调用方可安全长期持有（livecfg 快照要求不可变）。
func (c *Config) ClientKeys() map[string]string {
	out := make(map[string]string, len(c.APIKeys)+1)
	for k, v := range c.APIKeys {
		if k == "" || k == c.APIKey {
			continue
		}
		out[k] = v
	}
	if c.APIKey != "" {
		out[c.APIKey] = c.APIKeyName
	}
	if len(out) == 0 {
		return nil
	}
	return out
}

// normalizeAPIKeys 规整密钥表：TrimSpace、去空行、限量、名字截断。
//
// 密钥一律 TrimSpace：HTTP 头解析本就会去掉首尾空白，配置文件里从剪贴板粘进来的
// 尾随换行/空格如果不清掉，会变成"密钥明明是对的却一直 401"这种极难查的故障。
func (c *Config) normalizeAPIKeys() error {
	c.APIKey = strings.TrimSpace(c.APIKey)

	c.APIKeyName = clampKeyName(strings.TrimSpace(c.APIKeyName))
	if c.APIKeyName == "" {
		c.APIKeyName = DefaultAPIKeyName
	}

	if len(c.APIKeys) > 0 {
		cleaned := make(map[string]string, len(c.APIKeys))
		for k, v := range c.APIKeys {
			k = strings.TrimSpace(k)
			if k == "" {
				continue // 空密钥行（面板表单里删剩的一行）直接忽略
			}
			cleaned[k] = clampKeyName(strings.TrimSpace(v))
		}
		if len(cleaned) > MaxAPIKeys {
			return fmt.Errorf("api_keys: 共 %d 条，超出上限 %d 条", len(cleaned), MaxAPIKeys)
		}
		if len(cleaned) == 0 {
			cleaned = nil
		}
		c.APIKeys = cleaned
	}
	if len(c.APIKeyPolicies) > 0 {
		cleaned := make(map[string]livecfg.KeyPolicy, len(c.APIKeyPolicies))
		for id, policy := range c.APIKeyPolicies {
			id = strings.TrimSpace(id)
			if id == "" {
				continue
			}
			if policy.MaxConcurrency < 0 || policy.MaxConcurrency > 100 {
				return fmt.Errorf("api_key_policies.%s.max_concurrency: %d 非法（需为 0-100）", id, policy.MaxConcurrency)
			}
			seen := map[string]bool{}
			models := make([]string, 0, len(policy.Models))
			for _, model := range policy.Models {
				model = strings.TrimSpace(model)
				if model == "" || seen[model] {
					continue
				}
				seen[model] = true
				models = append(models, model)
			}
			policy.Models = models
			if len(models) > 64 {
				return fmt.Errorf("api_key_policies.%s.models: 共 %d 个，超出上限 64 个", id, len(models))
			}
			if len(policy.Models) > 0 || policy.MaxConcurrency > 0 {
				cleaned[id] = policy
			}
		}
		if len(cleaned) == 0 {
			cleaned = nil
		}
		c.APIKeyPolicies = cleaned
	}
	return nil
}

// clampKeyName 按字符（非字节）截断名字，避免把中文砍成半个字。
func clampKeyName(s string) string {
	if s == "" {
		return ""
	}
	r := []rune(s)
	if len(r) > maxKeyNameRunes {
		return string(r[:maxKeyNameRunes])
	}
	return s
}
